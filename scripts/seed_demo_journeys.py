def render_itinerary(sample):
    lines = [
        f"# 旅のしおり：{sample['destination']}",
        "",
        "## 旅のハイライト",
        sample["highlight"],
        "",
    ]
    for day_number, (day_title, periods) in enumerate(sample["schedule"], start=1):
        lines.extend([f"## {day_number}日目｜{day_title}", ""])
        for period, stops in periods:
            lines.extend([f"### {period}", ""])
            for time, place, description in stops:
                lines.extend([f"- {time}｜{place}", f"  {description}", ""])
    lines.extend(["## 旅のメモ", sample["memo"], "", "## 予算の目安", f"1人あたり約{sample['budget']:,}円。交通・宿泊・食事を含む参考額です。", ""])
    return "\n".join(lines)


def main():
    with app.app_context():
        demo_users = (User.query
                      .filter(User.user_type == "traveler",
                              User.email.like("traveler%@demo.tabidea.local"),
                              User.username.like("旅行者デモ%"))
                      .order_by(User.id).all())
        if len(demo_users) < 9:
            raise SystemExit("旅行者デモアカウントが9件見つからないため、データは追加していません。")

        added = 0
        skipped = 0
        for index, sample in enumerate(SAMPLES):
            user = demo_users[index % len(demo_users)]
            existing = TravelPlan.query.filter_by(
                user_id=user.id, title=sample["title"], destination=sample["destination"]
            ).first()
            if existing:
                skipped += 1
                continue

            start_date = date.today() - timedelta(days=18 + index * 21)
            plan = TravelPlan(
                user_id=user.id,
                title=sample["title"],
                destination=sample["destination"],
                start_date=start_date,
                end_date=start_date + timedelta(days=sample["days"] - 1),
                days=sample["days"],
                num_people=sample["people"],
                budget=sample["budget"],
                theme=sample["theme"],
                preferences="アプリ確認用のサンプル旅行記です。",
                ai_response=render_itinerary(sample),
            )
            plan.travel_story = TravelStory(
                user_id=user.id,
                introduction=sample["intro"],
                is_public=True,
            )
            db.session.add(plan)
            added += 1

        if added:
            db.session.commit()
        print(f"サンプル旅行記を{added}件追加しました。既存の{skipped}件はそのままです。")


if __name__ == "__main__":
    main()
